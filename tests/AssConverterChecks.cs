using System;
using System.Collections.Generic;
using System.Drawing;
using System.Drawing.Imaging;
using System.Globalization;
using System.Linq;
using System.Text;
using BilibiliPotPlayer;

internal static class AssConverterChecks
{
    const string Signature = "; Script generated by DanmakuFactory v1.70\n; https://github.com/hihkm/DanmakuFactory/\n";
    static string Header(bool signed)
    {
        string header = CaptionClassificationChecks.Header;
        string style = header.Split('\n').First(s => s.StartsWith("Style: Default,"));
        string styles = String.Join("\n", new[] { "R2L", "L2R", "TOP", "BTM", "SP", "Novel" }.Select(s => style.Replace("Default,", s + ",")));
        return header.Replace("[Script Info]\n", "[Script Info]\n" + (signed ? Signature : "")).Replace("[Events]", styles + "\n[Events]");
    }
    static string Line(string style, string tags, int index = 0, int layer = 0)
    {
        string start = String.Format(CultureInfo.InvariantCulture, "0:{0:00}:{1:00}.00", index / 15, index % 15 * 4);
        string end = String.Format(CultureInfo.InvariantCulture, "0:{0:00}:{1:00}.00", index / 15, index % 15 * 4 + 3);
        return "Dialogue: " + layer + "," + start + "," + end + "," + style + ",,0,0,0,,{" + tags + "}event " + index + "\n";
    }
    internal static void Run(Action<bool, bool, string> equal)
    {
        Action<bool, string> check = (v, m) => equal(true, v, m);
        string stationary = Header(true) + Line("SP", @"\pos(960,540)\alpha&H00&");
        TextSource special = TimedText.Parse(stationary, "static.ass", ".ass")[0];
        check(special.Category == TextCategory.Advanced && special.Events.Count == 1 && special.Cues.Count == 0, "signed DF SP is advanced even for a single static event");
        check(special.AssRenderable && !special.ProtocolAdvanced && CaptionCatalog.CanUse(special), "DF SP remains playable libass ASS rather than an unsupported protocol");
        TextSource horizontal = TimedText.Parse(Header(true) + Line("SP", @"\move(1920,100,-300,100)"), "moving.ass", ".ass")[0];
        check(horizontal.Category == TextCategory.Advanced && horizontal.AssRenderable, "signed DF SP retains advanced classification for full-duration horizontal movement");

        string[] names = { "R2L", "L2R", "TOP", "BTM" }; int[] modes = { 1, 6, 5, 4 };
        for (int i = 0; i < names.Length; i++)
        {
            TextSource ordinary = TimedText.Parse(Header(true) + Line(names[i], @"\pos(960,540)"), "ordinary.ass", ".ass")[0];
            check(ordinary.Category == TextCategory.Danmaku && ordinary.Cues.Count == 1 && ordinary.Cues[0].Mode == modes[i], "signed DF " + names[i] + " maps to the correct Bilibili mode without a sample minimum");
        }
        var mixed = TimedText.Parse(Header(true) + String.Join("", names.Select(s => Line(s, @"\pos(960,100)"))) + Line("SP", @"\pos(960,540)") + Line("SP", @"\move(1920,200,-300,200)", 0, 1), "mixed.ass", ".ass");
        check(mixed.Count == 2 && mixed.Single(s => s.Category == TextCategory.Danmaku).Events.Count == 4 && mixed.Single(s => s.Category == TextCategory.Advanced).Events.Count == 2, "DF ordinary and SP styles split independently while sharing Layer values");
        check(mixed.Sum(s => s.Events.Count) == 6 && mixed.SelectMany(s => s.Events).Select(c => c.AssOrder).Distinct().Count() == 6, "converter classification preserves every raw ASS event and its original order");

        var unknown = TimedText.Parse(Header(true) + Line("TOP", @"\pos(960,100)") + Line("Novel", @"\pos(960,540)"), "unknown.ass", ".ass");
        check(unknown.Count == 2 && unknown.Single(s => s.Category == TextCategory.Danmaku).Events.Count == 1 && unknown.Single(s => s.Category == TextCategory.Uncertain).Events.Count == 1, "unknown styles use generic evidence without diluting known DF styles");
        StringBuilder dialogue = new StringBuilder(Header(true));
        for (int i = 0; i < 20; i++) dialogue.Append(Line("Novel", @"\pos(960,1000)", i));
        check(TimedText.Parse(dialogue.ToString(), "unknown-dialogue.ass", ".ass")[0].Category == TextCategory.Subtitle, "DF signature alone does not declare unknown styles to be danmaku");
        StringBuilder genericScroll = new StringBuilder(Header(true) + Line("TOP", @"\pos(960,100)"));
        for (int i = 0; i < 20; i++) genericScroll.Append(Line("Novel", @"\move(1920,100,-300,100)", i));
        var combined = TimedText.Parse(genericScroll.ToString(), "combined.ass", ".ass");
        check(combined.Count == 1 && combined[0].Category == TextCategory.Danmaku && combined[0].Events.Count == 21, "generic ordinary evidence and known converter styles merge into one ordinary source");
        check(TimedText.Parse(Header(false) + Line("SP", @"\pos(960,540)"), "unrelated.ass", ".ass")[0].Category == TextCategory.Uncertain, "SP without a converter signature is not automatically advanced");
        check(TimedText.Parse(Header(false).Replace("[Script Info]", "[Script Info]\nTitle: Script generated by DanmakuFactory v1.70") + Line("SP", @"\pos(960,540)"), "title.ass", ".ass")[0].Category != TextCategory.Advanced, "a converter name in the title is not a generator signature");
        check(TimedText.Parse(Header(false) + Line("SP", @"\pos(960,540)") + "; Script generated by DanmakuFactory v1.70\n", "body.ass", ".ass")[0].Category != TextCategory.Advanced, "converter detection is limited to the ASS header");
        check(TimedText.Parse(Header(true) + Line("TOP", @"\t(\frz360)"), "effect.ass", ".ass")[0].Category == TextCategory.Advanced, "known ordinary style does not downgrade real ASS effects");
        check(TimedText.Parse(Header(true) + Line("TOP", @"\move(bad)"), "malformed.ass", ".ass")[0].Category == TextCategory.Uncertain, "known ordinary style does not hide unparsed critical structures");
        check(!TimedText.Parse(Header(false) + Line("Default", @"\pos(960,540)"), "generic.ass", ".ass")[0].Analysis.Reason.Contains("DanmakuFactory"), "generic ASS diagnostics do not claim a converter signature");

        var export = DanmakuFactory.ConvertCues(new[] {
            new TextCue { Mode = 1, Text = "right to left" }, new TextCue { Mode = 6, Text = "left to right" },
            new TextCue { Mode = 5, Text = "top" }, new TextCue { Mode = 4, Text = "bottom" },
            new TextCue { Mode = 7, Text = "[0.5,0.5,\"1-1\",4,\"Static Mode 7\",0,0,0.5,0.5,4000,0,true,\"Arial\",1]" }
        }, "native export");
        var roundTrip = TimedText.Parse(AssScene.Script(export, export.Events), "native.ass", ".ass");
        check(roundTrip.Count == 2 && roundTrip.Single(s => s.Category == TextCategory.Danmaku).Cues.Select(c => c.Mode).OrderBy(m => m).SequenceEqual(new[] { 1, 4, 5, 6 }), "real bundled DF export round-trips its four ordinary style types");
        check(roundTrip.Single(s => s.Category == TextCategory.Advanced).Events.Single().Style == "SP" && roundTrip.Single(s => s.Category == TextCategory.Advanced).AssRenderable, "real bundled DF static Mode 7 is recognized as playable SP on reimport");
        check(roundTrip.SelectMany(s => s.Events).OrderBy(c => c.AssOrder).Select(c => c.AssFields).SequenceEqual(export.Events.Select(c => c.AssFields)), "native DF reimport preserves authored tags, styles, layers and composition order");

        using (var catalog = new CaptionCatalog(IntPtr.Zero, null, new CaptionOptions(), null, delegate { }))
        using (var scene = new AssScene())
        using (var bitmap = new Bitmap(480, 270, PixelFormat.Format32bppPArgb))
        {
            special.Enabled = true; catalog.Sources.Add(special); catalog.Revision++;
            scene.Render(bitmap, catalog, 1000, new List<DanmakuPlacement>());
            check(HasPixels(bitmap), "newly recognized static SP renders actual ASS glyphs");
            catalog.Options.AssEffectsEnabled = false; catalog.Revision++;
            scene.Render(bitmap, catalog, 1000, new List<DanmakuPlacement>());
            check(!HasPixels(bitmap), "advanced filter controls the newly recognized static SP");
        }
    }
    static bool HasPixels(Bitmap bitmap)
    {
        for (int y = 0; y < bitmap.Height; y++) for (int x = 0; x < bitmap.Width; x++) if (bitmap.GetPixel(x, y).A > 0) return true;
        return false;
    }
}
